def _load_test_cases(spec_store: Any, module: str) -> list[dict[str, Any]]:
    """Load all behavioral test cases for *module* from the spec store."""
    doc_ids = spec_store.list_documents(module=module)
    cases = []
    for doc_id in doc_ids:
        if "test_case" in doc_id:
            doc = spec_store.read(doc_id, requester_role="verification_agent")
            cases.extend(doc["content"].get("test_cases", []))
    return cases


def _load_property_specs(spec_store: Any, module: str) -> list[dict[str, Any]]:
    """Load all property specifications for *module* from the spec store."""
    doc_ids = spec_store.list_documents(module=module)
    specs = []
    for doc_id in doc_ids:
        if "property_spec" in doc_id:
            doc = spec_store.read(doc_id, requester_role="verification_agent")
            specs.extend(doc["content"].get("properties", []))
    return specs


