def _issue_certificate(
    module: str,
    tests_passed: int,
    tests_failed: int,
    properties_verified: list[str],
    coverage: str,
    decision_log_complete: bool,
) -> VerificationCertificate:
    """Construct a signed verification certificate."""
    return VerificationCertificate(
        certificate_id=str(uuid.uuid4()),
        module=module,
        timestamp=datetime.now(timezone.utc).isoformat(),
        behavioral_tests_passed=tests_passed,
        behavioral_tests_failed=tests_failed,
        properties_verified=properties_verified,
        spec_coverage=coverage,
        decision_log_complete=decision_log_complete,
        certified=True,
    )


def _store_certificate(
    spec_store: Any, cert: VerificationCertificate, module: str
) -> None:
    """
    Persist a verification certificate to the spec store.

    Certificates bypass the normal guard workflow because they originate from
    the verification agent, not from cross-zone communication.  We use a
    synthetic guard decision ID to satisfy the spec store's write requirement.

    TODO: Issue a proper "verification approved" event instead of a synthetic ID.
    """
    import uuid as _uuid
    from cleanroom.state import GuardClassification, make_guard_decision

    # Create a synthetic approved guard decision for the certificate write.
    synthetic_decision = make_guard_decision(
        direction="response",
        submitter="verification_agent",
        classification=GuardClassification.APPROVED,
        reason="Verification certificate — no cross-zone content.",
    )
    spec_store.store_guard_decision(synthetic_decision)

    spec_store.write(
        doc_type=SpecDocumentType.VERIFICATION_CERTIFICATE,
        module=module,
        content=dict(cert),
        guard_decision_id=synthetic_decision["request_id"],
        requester_role="verification_agent",
    )


def _build_rejection_message(
    test_results: dict[str, Any],
    property_results: dict[str, Any],
    coverage_result: dict[str, Any],
    decision_log_complete: bool,
) -> str:
    """Summarise all failure reasons into a single rejection string."""
    reasons = []
    if test_results["failed"] > 0:
        reasons.append(
            f"{test_results['failed']} behavioral test(s) failed: "
            f"{[f['test_id'] for f in test_results.get('failures', [])]}"
        )
    if not property_results["all_passed"]:
        reasons.append(f"Properties failed: {property_results['failures']}")
    if not coverage_result["complete"]:
        reasons.append(
            f"Spec coverage incomplete. Uncovered: {coverage_result['uncovered_requirements']}"
        )
    if not decision_log_complete:
        reasons.append("Decision log has entries without spec references.")
    return "; ".join(reasons) if reasons else "Unknown failure"
