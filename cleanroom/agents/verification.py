"""
cleanroom.agents.verification
~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~
LangGraph node for the verification agent (spec §6).

The verification agent independently certifies that implementation agent
output satisfies all behavioral specifications.  It is the only entity that
may issue verification certificates — the implementation agent explicitly
CANNOT self-certify (spec §5.4).

The verification agent does NOT require an LLM for its core function: running
deterministic behavioral test cases against the implementation.  An LLM is
optional for auditing the decision log (spec §11.1).

Verification process per module (spec §6.2):
  1. Load behavioral test cases from spec store.
  2. Load property specifications from spec store.
  3. Execute all behavioral test cases against the implementation.
  4. Run property checker (invariant verification).
  5. Check spec coverage: every spec requirement has a test.
  6. Review decision log: every implementation choice has a spec reference.
  7. If all pass: issue verification certificate.
  8. If any fail: return rejection with the specific spec reference that failed.
"""

from __future__ import annotations

import uuid
from datetime import datetime, timezone
from typing import Any

from cleanroom.state import (
    CleanRoomState,
    SpecDocumentType,
    VerificationCertificate,
    make_audit_entry,
)


def build_verification_agent_node(spec_store: Any, audit_logger: Any):
    """
    Factory that returns a LangGraph node for the verification agent.

    Parameters
    ----------
    spec_store:
        Read-only access to behavioral test cases and property specs.
    audit_logger:
        Used to record verification outcomes as pipeline health signals.

    Returns
    -------
    Callable[[CleanRoomState], dict]
        A LangGraph node function.
    """

    def verification_agent_node(state: CleanRoomState) -> dict[str, Any]:
        """
        Run all verification steps for the current module.

        On success, issues a VerificationCertificate and adds the module to
        ``completed_modules``.  On failure, returns the state unchanged with
        an error message for the implementation agent to act on.
        """
        current_module = state.get("current_module")
        if not current_module:
            return {"error": "verification_agent called with no current_module"}

        # Step 1 & 2: Load test cases and property specs from spec store.
        test_cases = _load_test_cases(spec_store, current_module)
        property_specs = _load_property_specs(spec_store, current_module)

        # Step 3: Execute behavioral test cases.
        test_results = _run_behavioral_tests(test_cases, current_module)

        # Step 4: Verify properties / invariants.
        property_results = _verify_properties(property_specs, current_module)

        # Step 5: Check spec coverage.
        coverage_result = _check_spec_coverage(test_cases, current_module)

        # Step 6: Audit decision log.
        decision_log_complete = _check_decision_log(state, current_module)

        # Step 7 / 8: Issue certificate or rejection.
        all_passed = (
            test_results["failed"] == 0
            and property_results["all_passed"]
            and coverage_result["complete"]
            and decision_log_complete
        )

        if all_passed:
            cert = _issue_certificate(
                module=current_module,
                tests_passed=test_results["passed"],
                tests_failed=test_results["failed"],
                properties_verified=property_results["verified"],
                coverage=coverage_result["percentage"],
                decision_log_complete=decision_log_complete,
            )

            # Persist the certificate to the spec store.
            # The certificate is a spec store document (spec §7.2).
            # We use a synthetic approved guard decision ID here because
            # certificates are generated by verification, not by the analysis team.
            _store_certificate(spec_store, cert, current_module)

            audit_entry = make_audit_entry(
                event_type="cert_issued",
                agent_id="verification_agent",
                details={
                    "module": current_module,
                    "certificate_id": cert["certificate_id"],
                    "certified": True,
                    "tests_passed": cert["behavioral_tests_passed"],
                },
            )

            return {
                "completed_modules": [
                    *state.get("completed_modules", []),
                    current_module,
                ],
                "audit_log": [*state.get("audit_log", []), audit_entry],
                "error": None,
            }

        else:
            # Build a rejection message with the specific failing spec references.
            rejection_reasons = _build_rejection_message(
                test_results, property_results, coverage_result, decision_log_complete
            )

            audit_entry = make_audit_entry(
                event_type="cert_issued",
                agent_id="verification_agent",
                details={
                    "module": current_module,
                    "certified": False,
                    "rejection_reasons": rejection_reasons,
                },
            )

            return {
                "error": f"Verification failed for '{current_module}': {rejection_reasons}",
                "audit_log": [*state.get("audit_log", []), audit_entry],
            }

    return verification_agent_node


def route_verification(state: CleanRoomState) -> str:
    """
    LangGraph conditional edge: route based on verification outcome.

    Returns
    -------
    str
        ``"certified"``       → END (module complete)
        ``"rejected"``        → implementation_agent (fix and resubmit)
    """
    if state.get("error"):
        return "rejected"

    current = state.get("current_module")
    if current in state.get("completed_modules", []):
        return "certified"

    return "rejected"


